"""Regenerate conformance/spec/seestar-spec-names.json from a seestar-spec checkout.

The spec (https://github.com/zmerlynn/seestar-spec, CC0-1.0) has one YAML card
per method and event under ``catalog/<service>/{methods,events}/``. This writes
only the names and the services that define them; no card content is copied.

Run: python3 tools/vendor_spec_names.py /path/to/seestar-spec
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "conformance" / "spec" / "seestar-spec-names.json"
NAME = re.compile(r"name:\s*['\"]?([^'\"\n]+)['\"]?\s*$")


def card_name(card: Path) -> str:
    for line in card.read_text().splitlines():
        match = NAME.match(line)
        if match:
            return match.group(1).strip()
    return card.stem


def names(catalog: Path, kind: str) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for service in sorted(p for p in catalog.iterdir() if (p / kind).is_dir()):
        for card in sorted((service / kind).glob("*.yaml")):
            found.setdefault(card_name(card), []).append(service.name)
    return dict(sorted(found.items()))


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    spec = Path(sys.argv[1])
    commit = subprocess.run(
        ["git", "-C", str(spec), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    doc = {
        "description": (
            "Method and event names from the zmerlynn/seestar-spec catalog, with the services "
            "that define each. Names only; generated by tools/vendor_spec_names.py. Used by "
            "crates/scopinator-seestar/tests/spec_names.rs."
        ),
        "source": "https://github.com/zmerlynn/seestar-spec",
        "commit": commit,
        "licence": "CC0-1.0",
        "basis": "static analysis of firmware 9.31 and 9.75 (app 3.3.2 / 3.4.0)",
        "methods": names(spec / "catalog", "methods"),
        "events": names(spec / "catalog", "events"),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"wrote {len(doc['methods'])} methods and {len(doc['events'])} events at {commit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
